/// Checkpoint failure rolls back fresh attempts/events; no candidate outbox reaches a Node.
#[test]
fn checkpoint_failure_rolls_back_whole_group_preparation() {
    let fixture = Fixture::new(2, true, false);
    fixture.authorize();
    for attempt in &fixture.originals {
        fixture.fact(attempt, 2, ExecutionPhase::Cancelled, 20);
    }
    let original = server_checkpoint_json(&fixture.controller.lock().unwrap()).unwrap();
    let sequence = fixture.events.latest_sequence().unwrap();
    let db = rusqlite::Connection::open(fixture.directory.path().join("events.sqlite3")).unwrap();
    let table: String = db
        .query_row(
            "SELECT name FROM sqlite_master WHERE type='table' AND name LIKE '%checkpoint%'",
            [],
            |row| row.get(0),
        )
        .unwrap();
    db.execute_batch(&format!("CREATE TRIGGER fail_checkpoint BEFORE INSERT ON {table} BEGIN SELECT RAISE(FAIL,'test checkpoint failure'); END;")).unwrap();
    assert!(fixture.tick(21).is_err());
    assert_eq!(
        server_checkpoint_json(&fixture.controller.lock().unwrap()).unwrap(),
        original
    );
    assert_eq!(fixture.events.latest_sequence().unwrap(), sequence);
    db.execute_batch("DROP TRIGGER fail_checkpoint").unwrap();
    fixture.tick(22).unwrap();
    assert_eq!(
        fixture
            .controller
            .lock()
            .unwrap()
            .bridge
            .attempt_history()
            .len(),
        4
    );
}

/// Real HTTP admits the closed Group command, rejects malformed authorization and preserves budgets.
#[tokio::test]
async fn group_http_contract_is_atomic_idempotent_and_separate_from_role_recovery() {
    let fixture = Fixture::new(2, true, false);
    let path = format!("/v1/groups/{}/recover", fixture.group_id);
    let baseline = server_checkpoint_json(&fixture.controller.lock().unwrap()).unwrap();
    for (method, malformed) in [
        ("GET", "/v1/groups//recovery"),
        ("POST", "/v1/groups//recover"),
    ] {
        let (status, _) = fixture
            .request(method, malformed, fixture.command(), 5)
            .await;
        assert!(status.contains("400"));
        assert_eq!(
            server_checkpoint_json(&fixture.controller.lock().unwrap()).unwrap(),
            baseline
        );
    }
    for variant in 0..4 {
        let mut body = fixture.command();
        match variant {
            0 => {
                body["schema_version"] = serde_json::json!("wrong");
            }
            1 => {
                body["members"][0]["repeat_authorized"] = serde_json::json!(false);
            }
            2 => {
                body["members"].as_array_mut().unwrap().pop();
            }
            _ => {
                body["members"][0]["expected_node_id"] = serde_json::json!("wrong");
            }
        }
        let (status, _) = fixture.request("POST", &path, body, 5).await;
        assert!(status.contains(if variant == 0 { "400" } else { "409" }));
        assert_eq!(
            server_checkpoint_json(&fixture.controller.lock().unwrap()).unwrap(),
            baseline
        );
    }
    let (status, result) = fixture.request("POST", &path, fixture.command(), 5).await;
    assert!(status.contains("202"));
    assert_eq!(result["command_receipt_is_stop_proof"], false);
    let (status, repeated) = fixture.request("POST", &path, fixture.command(), 25).await;
    assert!(status.contains("202"));
    assert_eq!(repeated["stop_intent"]["deadline_ms"], 105);
    for attempt in &fixture.originals {
        fixture.fact(attempt, 2, ExecutionPhase::Cancelled, 30);
    }
    fixture.tick(31).unwrap();
    let (status, view) = fixture
        .request(
            "GET",
            &format!("/v1/groups/{}/recovery", fixture.group_id),
            serde_json::Value::Null,
            32,
        )
        .await;
    assert!(status.contains("200"));
    assert_eq!(view["disposition"], "ContinuationPrepared");
    assert_eq!(
        view["stop_intent"]["replacements"]
            .as_object()
            .unwrap()
            .len(),
        2
    );
    assert_eq!(view["resources_released_by_recovery"], false);
}

