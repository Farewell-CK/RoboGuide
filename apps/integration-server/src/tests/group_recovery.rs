    assert_eq!(
        fixture
            .controller
            .lock()
            .unwrap()
            .bridge
            .attempt_history()
            .len(),
        1
    );
    fixture.fact(&fixture.originals[0], 2, ExecutionPhase::Cancelled, 20);
    fixture.tick(21).unwrap();
    let retry = fixture
        .controller
        .lock()
        .unwrap()
        .bridge
        .attempt_history()
        .into_iter()
        .find(|attempt| attempt.execution_id() != fixture.originals[0].execution_id())
        .unwrap();
    assert_eq!(retry.command().task_id().as_str(), "task-0");
