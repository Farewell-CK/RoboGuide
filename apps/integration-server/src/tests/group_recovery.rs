    let replacements = fixture
        .controller
        .lock()
        .unwrap()
        .bridge
        .attempt_history()
        .into_iter()
        .filter(|attempt| {
            !fixture
                .originals
                .iter()
                .any(|original| original.execution_id() == attempt.execution_id())
        })
        .collect::<Vec<_>>();
    fixture.fact(&replacements[0], 1, ExecutionPhase::Accepted, 22);
