def main() -> None:
    """Run only the explicitly requested owned software profile or independent byte verifier."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--verify", nargs=2, metavar=("OUTPUT", "INDEX"))
    parser.add_argument("--use-lifecycle", action="store_true")
    parser.add_argument("--large-transfer", action="store_true")
    parser.add_argument("--group-lifecycle", action="store_true")
    parser.add_argument("--content-reclamation", action="store_true")
    parser.add_argument("--authority-recovery", action="store_true")
    parser.add_argument("--monitoring-tools", type=Path)
    parser.add_argument("--async-workers", type=int, choices=range(1, 65), default=8)
    parser.add_argument("--process-workers", action="store_true")
    parser.add_argument("--artifact-retention", action="store_true")
    parser.add_argument("--content-archive", action="store_true")
    parser.add_argument("--scheduling-costs", action="store_true")
    parser.add_argument("--old-controller", type=Path)
    parser.add_argument(
        "--handoff-case",
        choices=(
            "complete",
            "expiry",
            "policy-change",
            "controller-restart",
            "revision",
            "revision-sql",
            "revision-restart",
            "revision-policy",
            "revision-expiry",
            "revision-mi",
        ),
    )
    parser.add_argument("--use-query-recovery", action="store_true")
    parser.add_argument("--use-query-case", choices=("manual", "automatic", "unresolved"))
    parser.add_argument(
        "--use-case", choices=("revoke", "expire", "backend-restart", "controller-restart")
    )
    arguments = parser.parse_args()
    if arguments.scheduling_costs and (
        arguments.handoff_case
        or arguments.group_lifecycle
        or arguments.use_case
        or arguments.use_query_recovery
        or arguments.use_query_case
    ):
        parser.error("--scheduling-costs composes the actual complete file/Node/restart profile")
    if arguments.content_archive and (not arguments.artifact_retention or arguments.handoff_case):
        parser.error("--content-archive requires the completed --artifact-retention file profile")
    if arguments.artifact_retention and (
        arguments.group_lifecycle
        or arguments.use_lifecycle
        or arguments.use_case
        or arguments.use_query_recovery
        or arguments.use_query_case
    ):
        parser.error(
            "--artifact-retention extends the completion or original handoff/revision profile"
        )
    if arguments.artifact_retention and arguments.handoff_case not in (
        None,
        "complete",
        "revision",
        "revision-mi",
    ):
        parser.error("--artifact-retention requires a complete original child publication profile")
    if (
        arguments.old_controller
        and not arguments.scheduling_costs
        and not (arguments.handoff_case or "").startswith("revision")
    ):
        parser.error("--old-controller requires an actual revision Memory or scheduling cost check")
    if (arguments.handoff_case or "").startswith("revision") and not arguments.process_workers:
        parser.error("revision Memory requires original OS-process exit evidence")
    if arguments.monitoring_tools and not arguments.authority_recovery:
        parser.error("--monitoring-tools requires the actual --authority-recovery fault profile")
    if (arguments.content_reclamation or arguments.authority_recovery) and (
        arguments.group_lifecycle
        or arguments.handoff_case
        or arguments.use_query_recovery
        or arguments.use_query_case
        or arguments.use_case
    ):
        parser.error("reclamation/recovery extend the independently verified completion profile")
    if arguments.group_lifecycle and (
        arguments.use_lifecycle or arguments.use_case or arguments.large_transfer
    ):
        parser.error("--group-lifecycle is a separate bounded software profile")
    if arguments.verify:
        print(json.dumps(verify(Path(arguments.verify[0]), int(arguments.verify[1]))))
    elif arguments.output:
        print(
            json.dumps(
                run(
                    arguments.output,
                    arguments.use_lifecycle,
                    arguments.use_case,
                    arguments.large_transfer,
                    arguments.group_lifecycle,
                    arguments.use_query_recovery or arguments.use_query_case is not None,
                    arguments.use_query_case or "manual",
                    arguments.handoff_case,
                    arguments.content_reclamation,
                    arguments.authority_recovery,
                    arguments.monitoring_tools,
                    arguments.async_workers,
                    arguments.process_workers,
                    arguments.old_controller,
                    arguments.artifact_retention,
                    arguments.content_archive,
                    arguments.scheduling_costs,
                ),
                sort_keys=True,
            )
        )
    else:
        parser.error("--output or --verify is required")


if __name__ == "__main__":
    main()
