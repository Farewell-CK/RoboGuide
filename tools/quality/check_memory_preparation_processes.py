"""Exercise actual pre-Execute file Memory through two enrolled software Nodes and mutual TLS.

The positive work is real file hashing, transfer and independent recomputation. No robot,
simulator, model response or physical stopping evidence is generated by this profile.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import sqlite3
import ssl
import subprocess
import sys
import time
import uuid
from pathlib import Path
from typing import Any, BinaryIO

from check_identity_processes import request as tls_request
from check_state_verifier_processes import ROOT, address, request, save, stop, wait_for
from memory_preparation_profile import configuration, mission, node_environment, tls
from spatial_content_policy import digest


def identity() -> dict[str, str]:
    """Pin the actual binaries, maintained checker and backend source before process admission."""
    paths = [ROOT / "target/debug" / name for name in ("integration-server", "roboguide-node")]
    paths += [Path(__file__), Path(__file__).with_name("memory_preparation_profile.py")]
    paths += sorted((ROOT / "integrations/memory-provider/roboguide_memory_provider").glob("*.py"))
    paths += [
        Path(__file__).with_name(name)
        for name in (
            "check_memory_processes.py",
            "check_state_verifier_processes.py",
            "check_identity_processes.py",
            "check_artifact_authority_processes.py",
            "spatial_content_policy.py",
        )
    ]
    result = {
        str(path.relative_to(ROOT)): "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()
        for path in paths
    }
    result["python-executable"] = (
        "sha256:" + hashlib.sha256(Path(sys.executable).read_bytes()).hexdigest()
    )
    return result


def verify(directory: Path, index: int) -> dict[str, Any]:
    """Independently read actual original/backend bytes and the persisted CPU result."""
    manifest = json.loads((directory / "manifest.json").read_bytes())
    attempt = json.loads((directory / f"attempt-{index}.json").read_bytes())
    result = json.loads((directory / f"computation-{index}.json").read_bytes())["result"]
    source = (
        directory / "source/node-state/memory/files/source.bin"
        if index == 0
        else directory / "consumer/backend/content" / manifest["artifact"]["content_digest"][7:]
    )
    with source.open("rb") as stream:
        observed = "sha256:" + hashlib.file_digest(stream, "sha256").hexdigest()
    assert observed == manifest["artifact"]["content_digest"]
    assert source.stat().st_size == manifest["artifact"]["byte_size"]
    assert result["schema"] == "roboguide.file-hash-result/v0.1"
    assert result["execution_id"] == attempt["execution_id"]
    assert result["input_digests"] == [observed] and result["rounds"] == 2
    # This verifier intentionally does not import the provider's hashing/result helper.
    encoded = json.dumps(
        {"input_digests": [observed], "rounds": 2}, sort_keys=True, separators=(",", ":")
    ).encode()
    assert result["output_digest"] == "sha256:" + hashlib.sha256(encoded).hexdigest()
    return {
        "passed": True,
        "source_digest": observed,
        "execution_id": attempt["execution_id"],
        "result_digest": result["output_digest"],
    }


def run(directory: Path) -> dict[str, Any]:
    """Use only public Controller APIs, formal Node commands and actual local file backends."""
    directory.mkdir(mode=0o700, parents=True, exist_ok=False)
    directory = directory.resolve()
    initial_identity = identity()
    save(directory / "source-identity.json", initial_identity)
    nodes = [uuid.uuid4().hex for _ in range(2)]
    mission_id, memory_id, revision = (uuid.uuid4().hex for _ in range(3))
    grpc, operator, artifact = (address() for _ in range(3))
    origin, cas = "https://" + operator, "https://" + artifact
    backends = ["http://" + address() for _ in range(2)]
    environment = {
        key: value
        for key, value in os.environ.items()
        if not key.startswith(("ROBOGUIDE_", "OPENAI_", "EMOS_"))
    }
    environment["PYTHONPATH"] = str(ROOT / "integrations/memory-provider")
    contexts, leaves = tls(directory, nodes, memory_id, environment)
    source_root = directory / "source/node-state/memory/files"
    source_root.mkdir(parents=True)
    source = ROOT / "core/domain/src/memory.rs"
    shutil.copyfile(source, source_root / "source.bin")
    payload = source.read_bytes()
    manifest: dict[str, Any] = {
        "schema": "roboguide.memory-manifest/v0.1",
        "selector": {"memory_id": memory_id, "revision_id": revision},
        "kind": "artifact",
        "provider_id": "files",
        "owner": {"owner": "node", "node_id": nodes[0], "local_system_id": "posix-compute"},
        "scope": {"kind": "global"},
        "visibility": "exchangeable",
        "payload_schema": "roboguide.software-source-file/v0.1",
        "media_type": "application/octet-stream",
        "artifact": {
            "content_digest": "sha256:" + hashlib.sha256(payload).hexdigest(),
            "byte_size": len(payload),
        },
        "source_mission_id": None,
        "source_task_ref": None,
        "source_execution_id": None,
        "created_at": time.time_ns() // 1_000_000,
    }
    save(directory / "manifest.json", manifest)
    save(directory / "source/exports.json", [{"manifest": manifest, "artifact_path": "source.bin"}])
    logs: list[BinaryIO] = []
    processes: list[subprocess.Popen[bytes]] = []

    def start(
        arguments: list[str], name: str, env: dict[str, str] | None = None
    ) -> subprocess.Popen[bytes]:
        """Retain and reap only this invocation's actual OS processes."""
        log = (directory / (name + ".log")).open("wb")
        logs.append(log)
        process = subprocess.Popen(
            arguments,
            cwd=ROOT,
            env=environment if env is None else env,
            stdout=log,
            stderr=log,
            start_new_session=True,
        )
        processes.append(process)
        return process

    def exchange(
        path: str,
        body: dict[str, Any] | None = None,
        *,
        context: ssl.SSLContext | None = None,
        endpoint: str = origin,
    ) -> tuple[int, dict[str, Any]]:
        """Keep the actual certificate identity independent of JSON metadata and Node IDs."""
        return tls_request(endpoint, context or contexts["admin"], path, body)

    def preparations() -> dict[str, Any]:
        """Read only application-committed pre-execution authority."""
        value = exchange("/v1/memory/preparations")[1]["records"]
        if not isinstance(value, dict):
            raise ValueError("Memory preparation view is not an object")
        return value

    controller_command = [
        str(ROOT / "target/debug/integration-server"),
        grpc,
        str(directory / "controller.sqlite3"),
        operator,
        artifact,
        str(directory / "cas"),
    ]
    controller: subprocess.Popen[bytes] | None = None
    backend_processes: list[subprocess.Popen[bytes]] = []
    backend_commands: list[list[str]] = []
    node_processes: list[subprocess.Popen[bytes]] = []
    try:
        for index, name in enumerate(("source", "consumer")):
            owned = directory / name
            owned.mkdir(exist_ok=True)
            config = owned / "node.toml"
            config.write_text(
                configuration(owned, nodes[index], grpc, backends[index], cas, index == 1)
            )
            command = [
                sys.executable,
                "-m",
                "roboguide_memory_provider",
                "--root",
                str(owned / "backend"),
                "--provider-id",
                "files",
                "--input-root",
                str(owned),
                "--enable-file-jobs",
                "--listen-port",
                backends[index].rsplit(":", 1)[1],
            ]
            if index == 0:
                command += [
                    "--export-config",
                    str(owned / "exports.json"),
                    "--export-directory",
                    str(source_root),
                ]
            backend_commands.append(command)
            backend_processes.append(start(command, name + "-backend"))
            wait_for(
                lambda index=index: (
                    request(backends[index], "/v1/file-jobs/health")[1].get("ready") is True
                ),
                "actual file backend readiness",
            )
        # Abort actual SQL completion after fsynced copying, retaining original bytes and identity.
        with sqlite3.connect(directory / "consumer/backend/memory.sqlite3") as connection:
            connection.execute(
                "CREATE TRIGGER fail_final_import BEFORE UPDATE OF state ON imports "
                "BEGIN SELECT RAISE(ABORT,'original import completion crash window'); END"
            )
        controller = start(controller_command, "controller")
        wait_for(lambda: exchange("/healthz")[0] == 200, "actual Controller startup")
        for index, name in enumerate(("enrolment-first", "enrolment-next")):
            status, response = exchange(
                "/v1/node-identities/commands",
                {
                    "command_id": uuid.uuid4().hex,
                    "node_id": nodes[index],
                    "expected_revision": 0,
                    "action": {
                        "kind": "register",
                        "tenant_id": "local",
                        "domain_id": "software-files",
                        "digest": leaves[name],
                        "expires_at_ms": 0,
                    },
                },
            )
            assert status == 200, response
        policy: dict[str, Any] = {
            "policy_id": "immutable-source-" + uuid.uuid4().hex,
            "selector": manifest["selector"],
            "manifest_digest": digest(manifest),
            "tenant_id": "local",
            "principals": {
                "file-node-0": ["discover", "read"],
                "independent-file-reader": ["discover", "read"],
            },
            "groups": [],
            "revoked": False,
        }
        registry = {
            "schema_version": "roboguide.memory-authorization/v0.2",
            "registry_id": uuid.uuid4().hex,
            "revision": 1,
            "policies": {memory_id + "/" + revision: policy},
        }
        status, response = exchange(
            "/v1/memory-authorizations",
            {"command_id": uuid.uuid4().hex, "expected_revision": 0, "registry": registry},
        )
        assert status == 200, response
        verifier = {
            "source_id": "independent-file-reader",
            "revision": 1,
            "tenant_id": "local",
            "producer_principals": ["independent-file-reader"],
            "verifier": {"namespace": "observation", "name": "verify", "version": "v1"},
            "predicates": ["all file digests match"],
            "max_age_ms": 10000,
            "stop_timeout_ms": 5000,
            "enabled": True,
            "continuous": False,
            "require_artifact": False,
        }
        status, response = exchange(
            "/v1/verifier-sources",
            {
                "command_id": uuid.uuid4().hex,
                "expected_revision": 0,
                "registry": {
                    "schema_version": "roboguide.semantic-verifier-registry/v0.1",
                    "registry_id": uuid.uuid4().hex,
                    "revision": 1,
                    "sources": {"independent-file-reader": verifier},
                },
            },
        )
        assert status == 200, response
        configuration_paths = [directory / name / "node.toml" for name in ("source", "consumer")]
        configuration_paths += [
            directory / "source/exports.json",
            directory / "manifest.json",
            directory / "operator-authorization.json",
            directory / "artifact-authorization.json",
        ]
        configuration_identity = {
            str(path.relative_to(directory)): "sha256:"
            + hashlib.sha256(path.read_bytes()).hexdigest()
            for path in configuration_paths
        }
        for index, name in enumerate(("source", "consumer")):
            node_processes.append(
                start(
                    [
                        str(ROOT / "target/debug/roboguide-node"),
                        str(directory / name / "node.toml"),
                    ],
                    name + "-node",
                    node_environment(
                        environment,
                        directory,
                        "enrolment-first" if index == 0 else "enrolment-next",
                    ),
                )
            )
        wait_for(
            lambda: len(exchange("/v1/inventory")[1]["nodes"]) == 2,
            "two actual software Node registrations",
        )
        path = f"/v1/memories/{memory_id}/revisions/{revision}"
        published = wait_for(
            lambda: exchange(path, context=contexts["viewer"], endpoint=cas)[1].get("manifest"),
            "actual source Node publication and CAS upload",
        )
        assert published == manifest, published
        accepted = mission(mission_id, manifest)
        save(directory / "mission.json", accepted)
        status, response = exchange("/v1/missions", accepted)
        assert status == 202, response
        receipts = []
        for index in range(2):
            task_id = "hash-" + str(index)
            if index == 1:
                waiting = wait_for(
                    lambda: next(
                        (
                            record
                            for record in preparations().values()
                            if record["phase"] == "waiting_source"
                        ),
                        None,
                    ),
                    "Memory requirement waits for an explicit Group content grant",
                )
                with sqlite3.connect(
                    directory / "consumer/backend/file-jobs.sqlite3"
                ) as connection:
                    assert connection.execute("SELECT COUNT(*) FROM jobs").fetchone()[0] == 0
                save(directory / "before-group-grant.json", waiting)
                group_id = exchange("/v1/execution-attempts")[1]["attempts"][0]["group_id"]
                policy["groups"] = [
                    {
                        "group_id": group_id,
                        "operations": ["read", "import"],
                        "providers": [
                            {
                                "provider_id": None,
                                "local_system_id": None,
                                "kind": "artifact",
                                "payload_schema": manifest["payload_schema"],
                                "media_type": manifest["media_type"],
                            }
                        ],
                    }
                ]
                registry["revision"] = 2
                status, response = exchange(
                    "/v1/memory-authorizations",
                    {"command_id": uuid.uuid4().hex, "expected_revision": 1, "registry": registry},
                )
                assert status == 200, response
            completed = wait_for(
                lambda task_id=task_id: [
                    item
                    for item in exchange("/v1/execution-attempts")[1]["attempts"]
                    if item["task_id"] == task_id and item["status"] == "Completed"
                ],
                "actual original file computation completes",
                35,
            )
            assert len(completed) == 1
            attempt = completed[0]
            assert attempt["node_id"] == nodes[index]
            save(directory / f"attempt-{index}.json", attempt)
            status, computation = request(
                backends[index],
                "/v1/file-jobs/status",
                {"execution_id": attempt["execution_id"]},
                method="GET",
            )
            assert status == 200 and computation["state"] == "COMPLETED", computation
            save(directory / f"computation-{index}.json", computation)
            checked = subprocess.run(
                [sys.executable, str(Path(__file__)), "--verify", str(directory), str(index)],
                capture_output=True,
                check=True,
                timeout=10,
            )
            independent = json.loads(checked.stdout)
            assert independent["passed"] is True
            save(directory / f"independent-verifier-{index}.json", independent)
            evidence = {
                "evidence_id": uuid.uuid4().hex,
                "source_id": "independent-file-reader",
                "source_revision": 1,
                "tenant_id": "local",
                "task_ref": {"mission_id": mission_id, "task_id": task_id},
                "plan_digest": exchange(f"/v1/missions/{mission_id}/tenant")[1][
                    "source_plan_digest"
                ],
                "attempts": [
                    {"role_id": attempt["role_id"], "attempt_id": attempt["execution_id"]}
                ],
                "predicate": "all file digests match",
                "verdict": "satisfied",
                "finality": "final",
                "source_observed_at_ms": time.monotonic_ns() // 1_000_000,
                "valid_for_ms": 10000,
                "sequence": 1,
                "artifact_digest": None,
                "artifact_size_bytes": None,
            }
            status, response = exchange(
                "/v1/verifier-evidence", evidence, context=contexts["viewer"]
            )
            assert status == 200 and response["receipt"]["applied"] is True, response
            receipts.append(response)
        wait_for(
            lambda: exchange(f"/v1/missions/{mission_id}")[1]["status"] == "Completed",
            "independently satisfied Mission",
        )
        prepared = preparations()
        save(directory / "preparations.json", prepared)
        assert len(prepared) == 1
        record = next(iter(prepared.values()))
        assert (
            record["phase"] in {"ready", "revoking", "revoked"} and record["probe_generation"] == 1
        )
        statuses = {item["receipt"]["status"] for item in record["controls"].values()}
        assert {"prepared", "available"}.issubset(statuses)
        import_id = record["preparation"]["inputs"][0]["import_id"]
        original = exchange("/v1/memory/imports/" + import_id)[1]
        save(directory / "imports.json", {import_id: original})
        assert original["phase"] == "completed" and original["reconciliation"]["resolved_by"] == 1
        with sqlite3.connect(directory / "consumer/backend/memory.sqlite3") as connection:
            assert connection.execute("SELECT COUNT(*),state FROM imports").fetchone() == (
                1,
                "pending",
            )
        with sqlite3.connect(directory / "consumer/backend/file-jobs.sqlite3") as connection:
            original_jobs = connection.execute("SELECT * FROM jobs").fetchall()
            assert len(original_jobs) == 1 and original_jobs[0][2] == "COMPLETED"
        original_budget = record["deadline_ms"]
        stop(controller)
        controller = start(controller_command, "controller-restored")
        wait_for(lambda: exchange("/healthz")[0] == 200, "actual Controller restored")
        restored = next(iter(preparations().values()))
        assert restored["deadline_ms"] == original_budget
        assert restored["phase"] in {"revoking", "revoked"}
        assert exchange(f"/v1/missions/{mission_id}")[1]["status"] == "Completed"
        wait_for(
            lambda: next(iter(preparations().values()))["phase"] == "revoked",
            "actual Node revocation ACK after Controller restore",
        )
        node_database = directory / "consumer/node-state/execution-journal.sqlite3"
        with sqlite3.connect(node_database) as connection:
            original_receiver = connection.execute(
                "SELECT preparation_json,budget_json,configuration_digest FROM memory_preparations"
            ).fetchall()
        instances = [request(backend, "/v1/instance")[1]["instance_id"] for backend in backends]
        for process in node_processes:
            stop(process)
        wait_for(
            lambda: all(
                item["liveness"] == "Unreachable" for item in exchange("/v1/inventory")[1]["nodes"]
            ),
            "actual route loss after both Node processes stop",
        )
        received_before = {
            item["node_id"]: item["received_at_ms"]
            for item in exchange("/v1/inventory")[1]["nodes"]
        }
        for process in backend_processes:
            stop(process)
        for index, name in enumerate(("source", "consumer")):
            start(backend_commands[index], name + "-backend-restored")
            wait_for(
                lambda index=index: (
                    request(backends[index], "/v1/instance")[1].get("instance_id")
                    == instances[index]
                ),
                "actual original backend instance reopens",
            )
            node_processes.append(
                start(
                    [
                        str(ROOT / "target/debug/roboguide-node"),
                        str(directory / name / "node.toml"),
                    ],
                    name + "-node-restored",
                    node_environment(
                        environment,
                        directory,
                        "enrolment-first" if index == 0 else "enrolment-next",
                    ),
                )
            )
        wait_for(
            lambda: (
                len(fresh := exchange("/v1/inventory")[1]["nodes"]) == 2
                and all(
                    item["liveness"] == "Reachable"
                    and item["received_at_ms"] > received_before[item["node_id"]]
                    for item in fresh
                )
            ),
            "new actual registration receipts from both restarted Nodes",
        )
        with sqlite3.connect(node_database) as connection:
            assert (
                connection.execute(
                    "SELECT preparation_json,budget_json,configuration_digest "
                    "FROM memory_preparations"
                ).fetchall()
                == original_receiver
            )
        with sqlite3.connect(directory / "consumer/backend/file-jobs.sqlite3") as connection:
            assert connection.execute("SELECT * FROM jobs").fetchall() == original_jobs
        assert next(iter(preparations().values()))["deadline_ms"] == original_budget
        assert exchange("/v1/memory/imports/" + import_id)[1]["phase"] == "completed"
        assert identity() == initial_identity, "pinned code or binary changed during conformance"
        assert {
            str(path.relative_to(directory)): "sha256:"
            + hashlib.sha256(path.read_bytes()).hexdigest()
            for path in configuration_paths
        } == configuration_identity
        result = {
            "passed": True,
            "devices": 0,
            "models": 0,
            "simulators": 0,
            "software_nodes": 2,
            "actual_hash_jobs": 2,
            "actual_imports": 1,
            "original_import_completion_sql_failure": True,
            "readonly_reconciliations": 1,
            "independent_verifiers": 2,
            "execute_before_group_grant": False,
            "restart_renewed_budget": False,
            "actual_node_restarts": 2,
            "actual_backend_restarts": 2,
            "original_receiver_budget_unchanged": True,
            "transport_profile": "actual-mutual-tls-and-enrolled-nodes",
            "source_manifest": manifest,
            "source_identity": initial_identity,
            "configuration_identity": configuration_identity,
            "runtime": {
                "python_version": sys.version,
                "python_executable": str(Path(sys.executable).resolve()),
                "openssl": ssl.OPENSSL_VERSION,
                "sqlite": sqlite3.sqlite_version,
            },
            "verifier_receipts": receipts,
        }
        save(directory / "result.json", result)
        return result
    except BaseException as error:
        save(
            directory / "failure.json", {"error": repr(error), "source_identity": initial_identity}
        )
        raise
    finally:
        for process in reversed(processes):
            stop(process)
        for log in logs:
            log.close()
        save(
            directory / "owned-process-exits.json",
            {
                "all_owned_processes_reaped": all(
                    process.poll() is not None for process in processes
                ),
                "processes": [
                    {"pid": process.pid, "returncode": process.returncode} for process in processes
                ],
            },
        )


def main() -> None:
    """Run only the explicitly requested owned software profile or independent byte verifier."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--verify", nargs=2, metavar=("OUTPUT", "INDEX"))
    arguments = parser.parse_args()
    if arguments.verify:
        print(json.dumps(verify(Path(arguments.verify[0]), int(arguments.verify[1]))))
    elif arguments.output:
        print(json.dumps(run(arguments.output), sort_keys=True))
    else:
        parser.error("--output or --verify is required")


if __name__ == "__main__":
    main()
